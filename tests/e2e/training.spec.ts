import { test, expect } from '@playwright/test';
test('biblioteca → rutina → serie → finalizar → historial persistente',async({page})=>{
  await page.emulateMedia({colorScheme:'light'});
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Movimiento, a tu ritmo.'})).toBeVisible();
  expect(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor)).toBe('rgb(250, 249, 245)');
  await expect(page.locator('.art svg').first()).toBeVisible();
  await expect(page.locator('.art svg path').first()).toHaveAttribute('fill','currentColor');
  await page.screenshot({path:'test-results/library-desktop-light.png',fullPage:true});
  await page.getByRole('searchbox').fill('sentadilla');
  await page.getByRole('link',{name:/Sentadilla sin peso/}).first().click();
  await expect(page).toHaveURL(/\/biblioteca\//);await expect(page.getByRole('heading',{level:1})).toBeVisible();
  await page.screenshot({path:'test-results/exercise-detail-desktop.png',fullPage:true});
  await page.goto('/');
  await page.getByRole('searchbox').fill('sentadilla');
  await expect(page.getByRole('heading',{name:'Sentadilla sin peso',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Rutinas',exact:true}).click();
  await page.getByRole('article').filter({has:page.getByRole('heading',{name:'Full body principiante'})}).getByRole('button',{name:'Empezar',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Sentadilla sin peso',exact:true})).toBeVisible();
  await page.getByLabel('Repeticiones',{exact:true}).fill('12');
  await page.getByRole('button',{name:'Registrar serie',exact:true}).click();
  await expect(page.getByText('12 reps',{exact:true})).toBeVisible();
  await page.waitForTimeout(2200);await page.screenshot({path:'test-results/session-active-desktop.png',fullPage:true});
  await page.reload();
  await expect(page.getByText('12 reps',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Finalizar entrenamiento'}).click();
  await expect(page).toHaveURL(/historial/);
  await expect(page.getByText('1 sesión guardada')).toBeVisible();
  await page.reload();await expect(page.getByText('1 sesión guardada')).toBeVisible();
  await page.getByRole('button',{name:'Enviar a OrionHealth'}).click();
  await expect(page.getByRole('link',{name:'Abrir OrionHealth'})).toHaveAttribute('href',/^orionhealth:\/\/import\?p=/);
  await expect(page.locator('[role="alert"]')).toHaveCount(0);
  expect(errors).toEqual([]);
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'test-results/history-desktop-light.png',fullPage:true});
  await page.emulateMedia({colorScheme:'dark'});await page.evaluate(()=>{document.documentElement.dataset.theme='dark'});
  await page.screenshot({path:'test-results/history-desktop-dark.png',fullPage:true});
  await page.emulateMedia({colorScheme:'light'});await page.evaluate(()=>{document.documentElement.dataset.theme='light'});
  await page.setViewportSize({width:390,height:844});await page.goto('/');
  await expect(page.getByRole('heading',{name:'Movimiento, a tu ritmo.'})).toBeVisible();
  await page.screenshot({path:'test-results/library-mobile-light.png',fullPage:true});
  await expect(page.getByRole('heading',{name:'Movimiento, a tu ritmo.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Menú',exact:true}).click();
  await expect(page.getByRole('link',{name:'Ajustes',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Ajustes',exact:true}).click();await page.getByRole('combobox',{name:'Tema',exact:true}).selectOption('dark');
  await page.getByRole('button',{name:'Guardar ajustes'}).click();await expect(page.getByText('Ajustes guardados.')).toBeVisible();
  await page.goto('/');await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  expect(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor)).toBe('rgb(18, 18, 17)');
  await page.screenshot({path:'test-results/library-mobile-dark.png',fullPage:true});
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.reload();await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  await page.context().setOffline(true);await page.goto('/historial');
  await expect(page.getByText('1 sesión guardada')).toBeVisible();
  await page.context().setOffline(false);
});
